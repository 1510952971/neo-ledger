  Future<void> settleMember({
    required int ledgerId,
    required int memberId,
    required double amount,
    required String direction,
    String? idempotencyKey,
  }) async {
    final payload = {
      'ledgerId': ledgerId,
      'memberId': memberId,
      'amount': (amount * 100).round(),
      'direction': direction,
    };
    await _idempotencyKeys.run(
      operation: 'native-settlement',
      request: payload,
      idempotencyKey: idempotencyKey,
      send: (key) =>
          postJson('/api/settlements', {...payload, 'idempotencyKey': key}),
    );
  }

