class NeoLedgerApi {
  factory NeoLedgerApi({
    MobileApiSessionStore? session,
    MobileIdempotencyKeyStore? idempotencyKeys,
    MobileApiTransport? transport,
  }) {
    final sessionStore =
        session ??
        transport?.session ??
        MobileApiSessionStore.secure(const FlutterSecureStorage());
    final keyStore =
        idempotencyKeys ??
        MobileIdempotencyKeyStore.secure(const FlutterSecureStorage());
    return NeoLedgerApi._(
      session: sessionStore,
      idempotencyKeys: keyStore,
      transport:
          transport ??
          MobileApiTransport(session: sessionStore, idempotencyKeys: keyStore),
    );
  }

  NeoLedgerApi._({
    required this._session,
    required this._idempotencyKeys,
    required this._transport,
  });

  final MobileApiSessionStore _session;
  final MobileIdempotencyKeyStore _idempotencyKeys;
  final MobileApiTransport _transport;
  // Native mobile builds talk to the same hosted account as the web client.
  // A user can still override this through the persisted server setting.

  String get baseUrl => _session.baseUrl;
  bool get hasSession => _session.hasSession;
  String get autoLogSecret => _session.autoLogSecret;

  Future<void> load() => _session.load();

  Future<SessionUser?> fetchSessionUser() async {
    final data = await getJson('/api/auth');
    if (data is! Map<String, dynamic> || data['authenticated'] != true) {
      return null;
    }
    final rawUser = data['user'];
    if (rawUser is! Map) throw const ApiException('账号状态响应缺少用户信息');
    return SessionUser.fromJson(Map<String, dynamic>.from(rawUser));
  }

  Future<String?> updateAvatar(String? dataUrl) async {
    final data = await patchJson('/api/auth', {'avatarUrl': dataUrl});
    if (data is! Map<String, dynamic>) {
      throw const ApiException('头像响应格式无效');
    }
    return data['avatarUrl'] as String?;
  }

  Future<String> updateDisplayName(String displayName) async {
    final data = await patchJson('/api/auth', {
      'displayName': displayName.trim(),
    });
    if (data is! Map<String, dynamic> || data['displayName'] is! String) {
      throw const ApiException('昵称更新响应格式无效');
    }
    return data['displayName'] as String;
  }

  Future<void> bindAccountEmail({
    required String email,
    required String code,
    String? currentPassword,
    String? newPassword,
  }) async {
    await patchJson('/api/auth', {
      'email': email.trim(),
      'code': code.trim(),
      if (currentPassword != null && currentPassword.isNotEmpty)
        'currentPassword': currentPassword,
      if (newPassword != null && newPassword.isNotEmpty)
        'newPassword': newPassword,
    });
  }

  Future<void> setBaseUrl(String value) => _session.setBaseUrl(value);

  /// This is the separate bearer secret generated by the web automatic-ledger
  /// connection. It must never be replaced with the normal login session
  /// cookie: the Android listeners run independently of the Flutter session.
  Future<void> setAutoLogSecret(String value) =>
      _session.setAutoLogSecret(value);

  Future<SessionUser> login({
    required String username,
    required String password,
    String? mfaCode,
  }) async {
    final response = await _transport.send(
      'POST',
      '/api/auth',
      body: {
        'action': 'login',
        'username': username,
        'password': password,
        if (mfaCode != null && mfaCode.trim().isNotEmpty)
          'mfaCode': mfaCode.trim(),
      },
      includeCookie: false,
    );
    await _session.captureSetCookieHeader(response.headers['set-cookie']);
    final data = _transport.decodeObject(response);
    final user = data['user'];
    if (user is! Map<String, dynamic>) throw const ApiException('登录响应缺少用户信息');
    return SessionUser.fromJson(user);
  }

  Future<SessionUser> register({
    required String username,
    required String email,
    required String displayName,
    required String password,
    String? code,
  }) async {
    final response = await _transport.send(
      'POST',
      '/api/auth',
      body: {
        'action': 'register',
        'username': username.trim(),
        'email': email.trim(),
        'displayName': displayName.trim(),
        'password': password,
        if (code != null && code.trim().isNotEmpty) 'code': code.trim(),
      },
      includeCookie: false,
    );
    await _session.captureSetCookieHeader(response.headers['set-cookie']);
    final data = _transport.decodeObject(response);
    final user = data['user'];
    if (user is! Map<String, dynamic>) {
      throw const ApiException('注册响应缺少用户信息');
    }
    return SessionUser.fromJson(user);
  }

