  Future<AnalysisSummary> fetchAnalysis(int ledgerId) async {
    final now = DateTime.now();
    final today =
        '${now.year.toString().padLeft(4, '0')}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
    final query = [
      'ledger=$ledgerId',
      'today=$today',
      'dimension=%E6%9C%88',
      'offset=${now.timeZoneOffset.inMinutes}',
      'hour=${now.hour}',
      'now=${Uri.encodeQueryComponent(now.toUtc().toIso8601String())}',
    ].join('&');
    final data = await getJson('/api/transactions/summary?$query');
    if (data is! Map<String, dynamic>) throw const ApiException('分析响应格式无效');
    return AnalysisSummary.fromJson(data);
  }

