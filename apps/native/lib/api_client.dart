      body['expandedCategories'] = expandedCategories;
    }
    if (homeModules != null) body['homeModules'] = homeModules;
    await patchJson('/api/preferences', body);
  }

  Future<bool> verifyPreferencesPin(String pin) async {
    try {
      final data = await postJson('/api/preferences', {'pin': pin});
      return data is Map<String, dynamic> && data['ok'] == true;
    } on ApiException catch (error) {
      if (error.statusCode == 401 || error.statusCode == 403) return false;
      rethrow;
    }
  }

