  Future<void> updateTransaction(
    TransactionItem item, {
    required String title,
    required double amount,
    required String type,
    required int accountId,
    required String category,
    String? mood,
    String? note,
    List<String> tags = const [],
    bool reimbursable = false,
    int discountAmountCents = 0,
    bool excludeFromBudget = false,
  }) async {
    if (item.ledgerId <= 0 || item.updatedAt == null) {
      throw const ApiException('流水缺少版本信息，请刷新后再编辑');
    }
    final occurred = DateTime.tryParse(item.occurredAt)?.toLocal();
    if (occurred == null) throw const ApiException('流水时间格式无效');
    final localDate = DateFormat("yyyy-MM-dd'T'HH:mm").format(occurred);
    await putJson('/api/transactions', {
      'id': item.id,
      'ledgerId': item.ledgerId,
      'accountId': accountId,
      'amount': amount,
      'type': type,
      'title': title,
      if (note != null && note.trim().isNotEmpty) 'note': note.trim(),
      if (tags.isNotEmpty) 'tags': tags,
      'reimbursable': reimbursable,
      'discountAmount': discountAmountCents / 100,
      'excludeFromBudget': excludeFromBudget,
      'mood': mood ?? item.mood ?? '刚需',
      'category': type == '支出' ? category : '其它',
      'incomeCategory': type == '收入' ? category : '其它收入',
      'occurredAt': localDate,
      'originalTimezone': item.originalTimezone,
      'expectedUpdatedAt': item.updatedAt,
    });
  }

