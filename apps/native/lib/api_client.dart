  Future<void> updatePreferences({
    String? theme,
    String? mobileThemeMode,
    bool? highContrast,
    String? defaultCurrency,
    bool? enabled,
    String? pin,
    bool? hideAmounts,
    bool? hapticsEnabled,
    bool? continuousEntry,
    bool? expandedCategories,
    List<String>? homeModules,
  }) async {
    final body = <String, dynamic>{};
    if (theme != null) body['theme'] = theme;
    if (mobileThemeMode != null) body['mobileThemeMode'] = mobileThemeMode;
    if (highContrast != null) body['highContrast'] = highContrast;
    if (defaultCurrency != null) body['defaultCurrency'] = defaultCurrency;
    if (enabled != null) body['enabled'] = enabled;
    if (pin != null && pin.trim().isNotEmpty) body['pin'] = pin.trim();
    if (hideAmounts != null) body['hideAmounts'] = hideAmounts;
    if (hapticsEnabled != null) body['hapticsEnabled'] = hapticsEnabled;
    if (continuousEntry != null) body['continuousEntry'] = continuousEntry;
