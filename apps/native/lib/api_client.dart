      items: (data['items'] as List<dynamic>? ?? const [])
          .whereType<Map<String, dynamic>>()
          .map(PendingTransaction.fromJson)
          .toList(),
      total:
          int.tryParse(response.headers['x-total-count'] ?? '') ??
          int.tryParse('${data['total'] ?? 0}') ??
          0,
      hasMore:
          response.headers['x-has-more'] == 'true' || data['hasMore'] == true,
    );
  }

