      if (data is! Map<String, dynamic>) {
        throw const ApiException('账本同步标记响应格式无效');
      }
      return '${data['revision'] ?? '0'}';
    } catch (_) {
      // Older self-hosted servers expose only transaction revisions. The
      // periodic full refresh remains the compatibility safety net there.
      final legacy = await getJson(
        '/api/transactions/revision?ledger=$ledgerId',
      );
      if (legacy is! Map<String, dynamic>) {
        throw const ApiException('账本同步标记响应格式无效');
      }
      return 'legacy:${legacy['revision'] ?? '0'}:${legacy['updatedAt'] ?? ''}';
    }
  }

