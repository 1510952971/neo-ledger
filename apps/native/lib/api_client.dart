    if (id == null) {
      if (parentId != null) body['parentId'] = parentId;
      await postJson(path, body);
      return;
    }
    body['id'] = id;
    if (isActive != null) body['isActive'] = isActive;
    body['parentId'] = parentId;
    await putJson(path, body);
  }

