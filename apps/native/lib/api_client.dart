class ApiException implements Exception {
  const ApiException(this.message, [this.statusCode]);

  final String message;
  final int? statusCode;

  @override
  String toString() => message;
}

class NeoLedgerApi {
  NeoLedgerApi({FlutterSecureStorage? storage})
    : _storage = storage ?? const FlutterSecureStorage();

  static const _cookieKey = 'neo_ledger_session_cookie';
  static const _baseUrlKey = 'neo_ledger_base_url';
  static const _autoLogSecretKey = 'neo_ledger_auto_log_secret';
  final FlutterSecureStorage _storage;
  String _baseUrl = 'http://localhost:3000';
  String? _cookie;
  String _autoLogSecret = '';

  String get baseUrl => _baseUrl;
  bool get hasSession => _cookie != null && _cookie!.isNotEmpty;
  String get autoLogSecret => _autoLogSecret;

  Future<void> load() async {
    _cookie = await _storage.read(key: _cookieKey);
    _baseUrl = await _storage.read(key: _baseUrlKey) ?? _baseUrl;
    _autoLogSecret = await _storage.read(key: _autoLogSecretKey) ?? '';
  }

  Future<void> setBaseUrl(String value) async {
    final normalized = value.trim().replaceFirst(RegExp(r'/$'), '');
    if (normalized.isEmpty) return;
    _baseUrl = normalized;
    await _storage.write(key: _baseUrlKey, value: normalized);
  }

  /// This is the separate bearer secret generated by the web automatic-ledger
  /// connection. It must never be replaced with the normal login session
  /// cookie: the Android listeners run independently of the Flutter session.
  Future<void> setAutoLogSecret(String value) async {
    _autoLogSecret = value.trim();
    if (_autoLogSecret.isEmpty) {
      await _storage.delete(key: _autoLogSecretKey);
    } else {
      await _storage.write(key: _autoLogSecretKey, value: _autoLogSecret);
    }
  }

  Future<SessionUser> login({
    required String username,
    required String password,
    String? mfaCode,
  }) async {
    final response = await _send(
      'POST',
      '/api/auth',
      body: {
        'action': 'login',
        'username': username,
        'password': password,
        if (mfaCode != null && mfaCode.trim().isNotEmpty)
          'mfaCode': mfaCode.trim(),
      },
      includeCookie: false,
    );
    _saveCookie(response);
    final data = _decode(response);
    final user = data['user'];
    if (user is! Map<String, dynamic>) throw const ApiException('登录响应缺少用户信息');
    return SessionUser.fromJson(user);
  }

