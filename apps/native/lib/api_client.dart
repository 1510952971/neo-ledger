    if (data is! Map<String, dynamic>) throw const ApiException('同步响应格式无效');
    return (data['synced'] as List<dynamic>? ?? const [])
        .map((value) => '$value')
        .toList();
  }

  /// Exports the complete server-side backup as the JSON document produced by
  /// `/api/data/export`. Keeping the raw document lets the native client pass
  /// it back to the restore endpoint without losing fields added by the web
  /// client in a newer backup schema.
  Future<String> exportBackup() async {
    final response = await _send('GET', '/api/data/export');
    return utf8.decode(response.bodyBytes);
  }

  /// Runs the server's validation-only or actual restore flow.
  Future<Map<String, dynamic>> restoreBackup(
    String rawBackup, {
    required bool dryRun,
    String? expectedPlanChecksum,
  }) async {
    final decoded = jsonDecode(rawBackup);
    if (decoded is! Map) throw const ApiException('备份必须是 JSON 对象');
    final body = Map<String, dynamic>.from(decoded);
    body['dryRun'] = dryRun;
    final response = await _send(
      'POST',
      '/api/data/restore',
      body: body,
      extraHeaders: {
        if (expectedPlanChecksum != null && expectedPlanChecksum.isNotEmpty)
          'x-restore-plan-checksum': expectedPlanChecksum,
      },
    );
    final data = _decodeAny(response);
    if (data is! Map<String, dynamic>) {
      throw const ApiException('恢复响应格式无效');
    }
    return data;
  }

  Future<dynamic> getJson(String path) async =>
      _decodeAny(await _send('GET', path));

  Future<dynamic> postJson(
    String path,
    Map<String, dynamic> body, {
    Map<String, String>? extraHeaders,
  }) async => _decodeAny(
    await _send('POST', path, body: body, extraHeaders: extraHeaders),
  );

  Future<dynamic> putJson(String path, Map<String, dynamic> body) async =>
      _decodeAny(await _send('PUT', path, body: body));

  Future<dynamic> patchJson(String path, Map<String, dynamic> body) async =>
      _decodeAny(await _send('PATCH', path, body: body));

  Future<dynamic> deleteJson(String path, Map<String, dynamic> body) async =>
      _decodeAny(await _send('DELETE', path, body: body));

  Future<http.Response> _send(
    String method,
    String path, {
    Map<String, dynamic>? body,
    bool includeCookie = true,
    Map<String, String>? extraHeaders,
  }) async {
    final uri = Uri.parse('$_baseUrl$path');
    final headers = <String, String>{
      'Accept': 'application/json',
      'Cache-Control': 'no-cache',
    };
    if (extraHeaders != null) headers.addAll(extraHeaders);
    if (body != null) headers['Content-Type'] = 'application/json';
    if (includeCookie && hasSession) headers['Cookie'] = _cookie!;
    try {
      final response = switch (method) {
        'POST' => await http.post(
          uri,
          headers: headers,
          body: body == null ? null : jsonEncode(body),
        ),
        'PUT' => await http.put(
          uri,
          headers: headers,
          body: body == null ? null : jsonEncode(body),
        ),
        'PATCH' => await http.patch(
          uri,
          headers: headers,
          body: body == null ? null : jsonEncode(body),
        ),
        'DELETE' => await http.delete(
          uri,
          headers: headers,
          body: body == null ? null : jsonEncode(body),
        ),
        _ => await http.get(uri, headers: headers),
      };
      if (response.statusCode < 200 || response.statusCode >= 300) {
        throw ApiException(_errorMessage(response), response.statusCode);
      }
      return response;
    } on ApiException {
      rethrow;
    } catch (error) {
      throw ApiException('无法连接 $_baseUrl：$error');
    }
  }

  Map<String, dynamic> _decode(http.Response response) {
    final value = _decodeAny(response);
    if (value is! Map<String, dynamic>) throw const ApiException('服务器响应格式无效');
    return value;
  }

  dynamic _decodeAny(http.Response response) {
    try {
      return jsonDecode(utf8.decode(response.bodyBytes));
    } catch (_) {
      throw const ApiException('服务器返回了无法解析的数据');
    }
  }

  String _errorMessage(http.Response response) {
    try {
      final decoded = jsonDecode(utf8.decode(response.bodyBytes));
      if (decoded is Map<String, dynamic>) {
        return '${decoded['error'] ?? decoded['message'] ?? '请求失败'}';
      }
    } catch (_) {}
    return '请求失败（HTTP ${response.statusCode}）';
  }

  void _saveCookie(http.Response response) {
    final raw = response.headers['set-cookie'];
    if (raw == null) return;
    final match = RegExp(r'(neo_ledger_session=[^;]+)').firstMatch(raw);
    if (match == null) return;
    _cookie = match.group(1);
    _storage.write(key: _cookieKey, value: _cookie);
  }

  Future<void> logout() async {
    _cookie = null;
    await _storage.delete(key: _cookieKey);
  }
